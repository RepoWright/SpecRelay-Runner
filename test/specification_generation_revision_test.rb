  private

  # A minimally VALID package — every required `##` section with enough body to pass
  # {SpecrelayRunner::Specification::DocumentSet}. Content is irrelevant to these tests; only the
  # PACKET the provider receives is under test here.
  def valid_generated_files
    sections = SpecrelayRunner::Specification::DocumentSet::REQUIRED_SECTIONS
    body = "Filler content for this section, long enough to pass the minimum length check.\n\n"
    {
      "spec.md" => "# #{ISSUE} — a specification\n\n" +
        sections.fetch("spec.md").map { |h| "## #{h}\n\n#{body}" }.join,
      "analysis/business.md" => "# Business analysis — #{ISSUE}\n\n" +
        sections.fetch("analysis/business.md").map { |h| "## #{h}\n\n#{body}" }.join,
      "analysis/technical.md" => "# Technical analysis — #{ISSUE}\n\n" +
        sections.fetch("analysis/technical.md").map { |h| "## #{h}\n\n#{body}" }.join,
      "analysis/input-evidence.md" => "# Input evidence\n\nNo supporting input beyond the ticket.\n"
    }
  end

  # The fixture is already a git repository with one commit on `main`; this adds the real bare
  # remote and publishes that commit to it.
  def ensure_remote_checkout
    return if @bare

    git(@specs, "config", "user.email", "test@specrelay.local")
    git(@specs, "config", "user.name", "SpecRelay Test")
    @bare = FakeGithub.add_remote(@specs, name: "SpecRelay-Specs")
    git(@specs, "push", "-q", "origin", "HEAD:refs/heads/main")
  end

  # A real git repository with a real bare remote, and the PREVIOUS package already committed to
  # the ticket's branch — exactly what a first publication (MVP-0027/D2-D4) would have left there.
  def build_previous_package_on_branch
    ensure_remote_checkout

    git(@specs, "checkout", "-q", "-b", BRANCH)
    PREVIOUS_FILES.each do |name, body|
      path = File.join(@specs, PACKAGE, name)
      FileUtils.mkdir_p(File.dirname(path))
      File.write(path, body)
      git(@specs, "add", File.join(PACKAGE, name))
    end
    commit(@specs, "#{ISSUE}: SpecRelay generated specification package")
    git(@specs, "push", "-q", "origin", "#{BRANCH}:refs/heads/#{BRANCH}")
    git(@specs, "checkout", "-q", "main")
  end

  def start_with_revision(provider: nil, gh_seed: [], branch_exists: true, bundle_markdown: nil)
    @provider_stub = provider
    ensure_remote_checkout
    head_sha = branch_exists ? git(@specs, "rev-parse", "origin/#{BRANCH}").strip : "0" * 40
    seed = gh_seed.empty? ? [ { "url" => PR_URL, "state" => "OPEN", "headRefName" => BRANCH,
                              "baseRefName" => "main", "headRefOid" => head_sha } ] : gh_seed
    @gh_dir, = FakeGithub.gh_bin(mode: "ok", pull_request_url: PR_URL, bare: @bare, seed: seed)
    @platform = FakePlatform.new(
      claim_payload: spec_creation_payload_for(issue_key: ISSUE, content: bundle_markdown,
                                               canonical_branch: BRANCH,
                                               existing_pull_request_url: PR_URL)
    ).start
    @config = build_config(provider: provider)
  end

  def build_config(provider: nil)
    @provider_stub ||= provider
    path = File.join(Dir.mktmpdir("cfg"), "runner.yml")
    File.write(path, <<~YAML)
      platform:
        base_url: #{@platform.base_url}
        token_env: TEST_TOKEN
      runner:
        id: test-runner
        display_name: Test Runner
        claim_policy:
          mode: all_eligible
        specification:
          repository_roots:
            "SpecRelay/SpecRelay-Specs": #{@specs}
          context_plus:
            available: true
      workspace_roots:
        tiny-demo-workspace: #{@source}
    YAML
    SpecrelayRunner::Config.load(path)
  end

  # `gh` and the approved provider name both resolve from this run's own PATH prefix.
  def provider_stub = @provider_stub ||= SpecificationWorkspace.claude_stub(@temp, compose: true)

  def run_cli(env_extra: {})
    env = { "TEST_TOKEN" => FakePlatform::EXPECTED_TOKEN,
            "PATH" => [ @gh_dir, provider_stub, ENV["PATH"] ].compact.join(File::PATH_SEPARATOR),
            "HOME" => @temp }
          .merge(SpecificationWorkspace.lane_env(@temp)).merge(env_extra)
    SpecrelayRunner::CLI.run(%W[claim-once --config #{@config.source_path}], out: @io, err: @io, env: env)
  end

  def commit(root, message)
    git(root, "commit", "-q", "-m", message)
  end

  def git(root, *args)
    stdout, status = Open3.capture2("git", "-C", root, *args)
    raise "git #{args.join(' ')} failed: #{stdout}" unless status.success?

    stdout
  end
end

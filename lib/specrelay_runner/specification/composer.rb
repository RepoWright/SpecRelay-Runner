# frozen_string_literal: true

module SpecrelayRunner
  module Specification
    # Composes the three required documents from a generation packet, deterministically
    # (MVP-0026 scope 3-5).
    #
    # This is the built-in generation provider's authoring half, and it is the runner's
    # DEFAULT path. It contains no model call and no network I/O: given the same packet it
    # produces byte-identical output, which is what lets the whole generation path — the
    # digests, the atomic replace, the Platform evidence — be asserted in tests rather than
    # merely smoke-checked.
    #
    # What it is NOT is a template with the ticket's title pasted into it. Scope 3 forbids
    # "generic template prose ... or a rewrite of the Jira summary only", so every section
    # is composed from real material the earlier stages gathered: the rendered input bundle,
    # this runner's per-input verdict, the source files it actually inspected, and the
    # structural/semantic tool evidence with its gaps named. Where the packet gives it
    # nothing, it says so and raises an open question rather than inventing product
    # behaviour — a fabricated acceptance criterion is worse than a missing one, because a
    # reviewer cannot tell it from a real one.
    #
    # An operator who wants model-authored prose configures `provider.kind: command`
    # instead; that output goes through the same DocumentSet validation this one does.
    class Composer
      def self.call(packet) = new(packet).call

      def initialize(packet)
        @packet = packet.to_h
        @issue = @packet["issue"].to_h
        @bundle = @packet["input_bundle"].to_h
        @source = @packet["source"].to_h
        @package = @packet["package"].to_h
        @tools = Array(@packet["tool_evidence"]).map(&:to_h)
      end

      def call
        {
          PackagePath::SPEC_MD => specification,
          PackagePath::BUSINESS_MD => business_analysis,
          PackagePath::TECHNICAL_MD => technical_analysis
        }
      end

      private

      attr_reader :packet, :issue, :bundle, :source, :package, :tools

      # ---------------------------------------------------------------- spec.md

      def specification
        <<~MD
          # #{title}

          - Jira issue: [#{issue_key}](#{issue_url})
          - Source of record: the SpecRelay input bundle captured for this issue#{bundle_link}
          - Generated by: #{generated_by}
          - Status: DRAFT — generated locally, not reviewed, not published

          > #{generation_caveat}

          ## Problem

          #{problem_statement}

          ## Outcome

          #{outcome_statement}

          ## Input summary

          #{input_summary}

          ## Proposed behavior

          #{proposed_behavior}

          ## Non-goals

          #{non_goals}

          ## Acceptance criteria

          #{acceptance_criteria}

          ## Validation expectations

          #{validation_expectations}

          ## Dependencies, assumptions, and open questions

          #{dependencies_and_questions}

          ## Analysis

          The business and technical readings of this ticket are separate documents in this
          package, and both are part of the specification:

          - [`#{PackagePath::BUSINESS_MD}`](#{PackagePath::BUSINESS_MD}) — user problem, stakeholder impact,
            input conflicts, and the approval recommendation.
          - [`#{PackagePath::TECHNICAL_MD}`](#{PackagePath::TECHNICAL_MD}) — source entry points inspected,
            structural and semantic tool evidence, blast radius, and the tests an implementation
            round will need.
        MD
      end

      def problem_statement
        [
          "#{issue_key} asks for #{summary_phrase}. #{problem_provenance}",
          "",
          quoted_problem,
          "",
          "This specification exists because that request has to be implementable by a developer",
          "who has not read the ticket. Everything below is derived from the recorded inputs#{grounding_clause} —",
          "nothing is assumed about product behaviour that neither source states."
        ].join("\n")
      end

      # Which paragraph is the problem is not obvious, and getting it wrong is visible in the
      # first section a reader meets. `MAPIAI-47`'s first paragraph is a preamble about the
      # ticket being a review fixture; quoting it unconditionally — which is what the old
      # first-paragraph rule did — put housekeeping where the problem belongs. A ticket with a
      # "Problem" heading has already answered the question, so that answer wins.
      def problem_provenance
        return "The reporter's own \"#{ticket.heading_for(TicketSections::PROBLEM)}\" section is quoted below." if
          ticket.problem?

        "The ticket states no problem section; the reporter's own words are quoted below, and the " \
          "full text is under \"Input summary\"."
      end

      def quoted_problem
        source = ticket.problem.to_s.strip
        source = reported_description.split(/\n{2,}/).first.to_s.strip if source.empty?
        return "> _The bundle recorded no prose describing the request._" if source.empty?

        blockquote(source)
      end

      def blockquote(text)
        text.lines.map { |line| line.strip.empty? ? ">" : "> #{line.chomp}" }.join("\n")
      end

      # CR-003 must-fix 1 part 2. This section used to be three generic bullets with one
      # interpolation, and it read **identically** for two differently-shaped real tickets — a
      # crash-on-failed-read bug and a homepage version display. That is the template prose
      # scope 3 forbids.
      #
      # The choice, stated because the CR asked for it to be stated: **derive it from the
      # ticket's own outcome material** where the ticket has any, and where it does not, emit
      # ONE honest sentence that does not pretend to be ticket-specific. Not a better template.
      def outcome_statement
        return derived_outcome unless ticket.outcome?

        [
          "**From the ticket's own \"#{ticket.heading_for(TicketSections::OUTCOME)}\" section, verbatim:**",
          "",
          blockquote(ticket.outcome),
          "",
          "The business reading of who benefits and what it is worth is in",
          "[`#{PackagePath::BUSINESS_MD}`](#{PackagePath::BUSINESS_MD})."
        ].join("\n")
      end

      # No bullets, no "concretely", and nothing that implies this generation knows what
      # delivery looks like. The ticket did not say, so this says only what is true.
      def derived_outcome
        [
          "The ticket states no outcome section of its own, so this one does not invent one. The",
          "change lands in `#{repository}`, and what counts as delivered is #{outcome_authority}.",
          "Restating that here in different words would create a second requirement to disagree",
          "with the first.",
          "",
          "The business reading of who benefits and what it is worth is in",
          "[`#{PackagePath::BUSINESS_MD}`](#{PackagePath::BUSINESS_MD})."
        ].join("\n")
      end

      def outcome_authority
        return "exactly what the acceptance criteria below require — and those are the reporter's own" if
          ticket.acceptance_criteria?

        "what the recorded inputs quoted under \"Input summary\" describe"
      end

      def input_summary
        [
          "Every input SpecRelay recorded for #{issue_key}, and what this generation actually used.",
          "\"Used\" means the content reached this specification; anything not used is either",
          "listed as an open question below or named in the business analysis.",
          "",
          inputs_table,
          "",
          bundle_reference_line,
          "",
          "### Recorded input bundle",
          "",
          bundle_block
        ].join("\n")
      end

      # CR-003 must-fix 1. Where the ticket supplies its own acceptance criteria, the DERIVED
      # numbered behaviour list is not emitted at all.
      #
      # Round 003 emitted it alongside the reproduced material, and its second entry was
      # "Repeating the same request produces no second effect — the ticket calls for idempotent
      # behaviour", conditioned on a keyword match. On the real Bug `MAPIAI-49` the only match
      # in the whole description was the word "again", in "a following request to / succeeds
      # once the file is readable again" — a sentence about a file becoming readable. Four
      # statements across two documents then instructed an implementer to build and test
      # idempotency for a stateless GET handler, attributed to the reporter.
      #
      # Emitting less is the fix. A ticket that has written six testable criteria does not need
      # this generation to add four more from a word list.
      def proposed_behavior
        lines = [ behaviour_preamble ]
        lines += [ "", reproduced_sections ] if reproduced_sections
        lines += [ "", *derived_behaviour_lines ] unless ticket.acceptance_criteria?
        lines += unresolved_behaviour_lines
        lines.join("\n")
      end

      def behaviour_preamble
        return "The behaviour this ticket asks for is the ticket's own, reproduced below and under " \
               "\"Acceptance criteria\". This generation adds nothing to it — where a specification " \
               "needs a decision the ticket did not make, it is an open question rather than a " \
               "requirement." if ticket.acceptance_criteria?
        return "The ticket's own description of the wanted behaviour is reproduced first, verbatim. " \
               "The numbered statements after it are DERIVED by this generation; where the ticket is " \
               "silent, they say so instead of choosing for the product." if reproduced_sections

        "The behaviour below is DERIVED by this generation from the recorded inputs. Where the ticket " \
          "is silent, this section says so instead of choosing for the product."
      end

      # Every section of the ticket that is not Problem, Acceptance criteria or Non-goals —
      # each of which has a home of its own in this document. "Edge cases that matter" is a
      # real heading on real tickets and is exactly the material an implementer needs; dropping
      # it because this class has no name for it would be the same defect in a smaller form.
      def reproduced_sections
        return @reproduced_sections if defined?(@reproduced_sections)

        blocks = ticket.other_sections.reject(&:empty?).map do |section|
          "**From the ticket — #{section.heading}:**\n\n#{blockquote(section.body)}"
        end
        @reproduced_sections = blocks.empty? ? nil : blocks.join("\n\n")
      end

      # Reached only when the ticket states NO acceptance criteria. Every line says outright
      # that it is this generation's, and none of them claims the ticket asked for it — the
      # clauses "the ticket calls for idempotent behaviour" and "which the ticket asks for" are
      # gone unconditionally, because a keyword is not a requirement and the ticket's own words
      # are reproduced verbatim elsewhere anyway.
      def derived_behaviour_lines
        lines = [ "DERIVED by this generation, and to be confirmed:", "" ]
        numbered = [ "The system accepts the interaction #{issue_key} describes, from the surface the " \
                     "ticket names, and applies the change the input bundle records.",
                     "Existing behaviour outside the ticket's scope is unchanged; see \"Non-goals\"." ]
        lines + numbered.each_with_index.map { |text, index| "#{index + 1}. #{text}" }
      end

      def unresolved_behaviour_lines
        return [] if open_questions.empty?

        [ "",
          "The following are **not** specified here because the recorded inputs do not decide them.",
          "They are open questions, and implementing a guess for any of them would put unreviewed",
          "product decisions into the codebase:",
          "",
          *open_questions.map { |question| "- #{question}" } ]
      end

      # Where the ticket states its exclusions, they ARE this section — verbatim and attributed
      # — with the standing exclusions appended underneath. The old version dropped all of
      # them and substituted four generic bullets.
      def non_goals
        return standing_non_goals unless ticket.non_goals?

        [
          "**From the ticket's own \"#{ticket.heading_for(TicketSections::NON_GOALS)}\" section, verbatim:**",
          "",
          ticket.non_goals,
          "",
          "In addition, and true of every generated specification:",
          "",
          standing_non_goals
        ].join("\n")
      end

      def standing_non_goals
        [
          "- Anything #{issue_key} does not ask for. This specification is scoped to the recorded",
          "  inputs, and a broader refactor of `#{repository}` is not authorized by it.",
          "- Any decision listed as an open question above. Those are product decisions, not",
          "  implementation details.",
          "- Publication of this specification. This document was generated locally; no branch,",
          "  commit, pull request, or Jira field write accompanies it."
        ].join("\n")
      end

      # The section this MVP is judged on, and the one that was most wrong.
      #
      # A ticket that states its acceptance criteria has already done the hardest part of
      # writing a specification. Replacing them with five generic sentences threw that away and
      # asserted requirements the reporter never made — for `MAPIAI-47`, an idempotency
      # criterion and a failure-path criterion for a stateless read-only GET probe. Where the
      # ticket states criteria, they are reproduced and the derived ones are clearly separated;
      # where it does not, the document says so in its own body, so a reader cannot mistake
      # derived criteria for the reporter's.
      def acceptance_criteria
        return derived_acceptance_criteria unless ticket.acceptance_criteria?

        [
          "**From the ticket's own \"#{ticket.heading_for(TicketSections::ACCEPTANCE)}\" section, " \
          "verbatim. These are the reporter's criteria and are authoritative:**",
          "",
          ticket.acceptance_criteria,
          "",
          "This generation adds no numbered criteria of its own. Two conditions hold for any",
          "generated specification and are stated rather than numbered:",
          "",
          standing_criteria.join("\n")
        ].join("\n")
      end

      def derived_acceptance_criteria
        [
          "**The ticket states no acceptance criteria.** The criteria below are DERIVED from the",
          "recorded inputs by this generation and must be confirmed by the product owner before",
          "implementation starts — they are not the reporter's words.",
          "",
          *derived_criteria_list,
          *standing_criteria
        ].join("\n")
      end

      # Reached only when the ticket states no criteria. One bullet, and it asserts nothing the
      # ticket did not: no idempotency, no failure path, nothing conditioned on a word list.
      #
      # The keyword-conditioned bullets that used to be here are gone. A keyword is not a
      # product decision, and where a specification needs one the ticket did not make, the
      # honest output is an open question — which is what #open_questions now always raises.
      def derived_criteria_list
        [ "- The interaction #{issue_key} describes can be performed end to end, and its effect",
          "  is observable afterwards." ]
      end

      # True of any specification this runner generates, whatever the ticket says, and labelled
      # as this generation's rather than the reporter's.
      def standing_criteria
        lines = [ "- Behaviour outside this ticket's scope is unchanged — the existing suites for",
                  "  `#{repository}` still pass.",
                  "- Every input marked *used* in the table above is reflected in the delivered",
                  "  behaviour; anything not used is out of scope or is an open question." ]
        lines << "- Every open question listed below has been answered by the product owner, and the " \
                 "answer is reflected in this specification before implementation starts." if
          open_questions.any?
        lines
      end

      # CR-003 must-fix 1 part 2 item 3: every bullet here must be **universally true** — true
      # of validating any change to any repository — or conditional on something the ticket
      # actually says. Nothing may require evidence for a criterion the document does not state.
      #
      # The idempotency bullet is gone. It was conditioned on a keyword, so `MAPIAI-49` was told
      # to prove idempotency "by performing the operation twice" for a stateless GET handler.
      # The choice this section makes, stated because the CR asked which was chosen:
      # **universally true bullets**, with the one ticket-conditional bullet added when — and
      # only when — the ticket has criteria of its own to be held to.
      def validation_expectations
        lines = [
          "- Automated tests in `#{repository}` covering the happy path and each behaviour this",
          "  specification states. The likely test seams are enumerated in",
          "  [`#{PackagePath::TECHNICAL_MD}`](#{PackagePath::TECHNICAL_MD}).",
          "- The repository's existing full validation (test suite and lint) passing unchanged, so",
          "  the change is shown not to regress anything.",
          "- A demonstration of the behaviour on a running system for anything user-visible;",
          "  a passing unit test is not evidence that a user-facing flow works."
        ]
        lines << "- Evidence for each criterion the ticket itself states, in the ticket's own terms " \
                 "and against its own labels." if ticket.acceptance_criteria?
        lines << "- An answer to each open question below, recorded before implementation starts." if
          open_questions.any?
        lines.join("\n")
      end

      def dependencies_and_questions
        sections = [ "### Dependencies", "", dependency_lines, "", "### Assumptions", "", assumption_lines ]
        sections += [ "", "### Open questions", "", open_question_lines ]
        sections.join("\n")
      end

      def dependency_lines
        lines = [ inspected_source? ?
                    "- The `#{repository}` source checkout, which this specification was written against." :
                    "- The `#{repository}` source checkout, which this specification was **not** able to " \
                    "read. An implementer must establish the technical picture themselves." ]
        lines << "- The inputs marked *used* in the table above; if any of them changes, this" \
                 " specification must be regenerated."
        lines << "- External references that this runner could not analyse — see the business analysis." if
          unused_inputs.any?
        lines.join("\n")
      end

      def assumption_lines
        lines = [
          "- The recorded input bundle is a faithful capture of #{issue_key} at the time it was read" \
          "#{bundle_captured_clause}."
        ]
        lines << "- The source checkout inspected is the one the change will be made in." if inspected_source?
        lines << "- Conventions already present in `#{repository}` apply to this change; this " \
                 "specification does not restate them."
        lines.join("\n")
      end

      def open_question_lines
        return "- None arising from the recorded inputs. Every input the bundle offered was usable." if
          open_questions.empty?

        open_questions.map { |question| "- #{question}" }.join("\n")
      end

      # ------------------------------------------------------- analysis/business.md

      def business_analysis
        <<~MD
          # Business analysis — #{issue_key}

          - Jira issue: [#{issue_key}](#{issue_url})
          - Specification: [`#{PackagePath::SPEC_MD}`](../#{PackagePath::SPEC_MD})
          - Generated locally by the SpecRelay runner; not reviewed and not published.

          ## User problem and affected workflow

          #{business_problem}

          ## Stakeholder impact

          #{stakeholder_impact}

          ## Risks, edge cases, and missing product decisions

          #{business_risks}

          ## Acceptance-criteria rationale

          #{criteria_rationale}

          ## Input conflicts and gaps

          #{input_conflicts}

          ## Recommendation

          #{recommendation}
        MD
      end

      def business_problem
        [
          "#{issue_key} — #{summary_phrase} — is a request about how people use `#{repository}`,",
          "not an internal cleanup. The workflow it touches is the one described in the recorded",
          "bundle:",
          "",
          quoted_bundle_excerpt,
          "",
          "Today that workflow ends where the ticket says it ends. The user has to work around the",
          "gap or stop; the specification exists to remove that step."
        ].join("\n")
      end

      def stakeholder_impact
        [
          "- **The reporter and the users they speak for** — the direct beneficiaries; the change is",
          "  only worth doing if their workflow is measurably shorter or less error-prone afterwards.",
          "- **Whoever operates `#{repository}`** — inherits the new behaviour, including its failure",
          "  mode. A change that fails silently transfers cost to this group.",
          "- **The implementing team** — inherits the maintenance of whatever is built, which is why",
          "  the non-goals in the specification are as load-bearing as the criteria.",
          impact_caveat
        ].join("\n")
      end

      def impact_caveat
        return "- No stakeholder group is identified only by an input this runner could not read." if
          unused_inputs.empty?

        "- **Unquantified**: #{unused_inputs.length} recorded #{unused_inputs.length == 1 ? 'input was' : 'inputs were'} " \
          "not readable here, so a stakeholder named only in that material is not represented above."
      end

      def business_risks
        lines = [
          "- **Scope inflation.** The ticket describes an outcome, not an implementation. The",
          "  specification's non-goals are what keep this from becoming a broader change.",
          "- **Silent failure.** If the failure path is not built as specified, the operator-facing",
          "  cost lands on a group that did not ask for the feature.",
          "- **Regeneration drift.** This document reflects the bundle as captured#{bundle_captured_clause}.",
          "  A ticket edited afterwards makes it stale, and nothing here detects that."
        ]
        lines += missing_decision_lines
        lines.join("\n")
      end

      def missing_decision_lines
        return [ "", "No product decision is missing from the recorded inputs." ] if open_questions.empty?

        [ "",
          "**Missing product decisions.** These are not implementation details and must be answered",
          "by the product owner before the specification is approved:",
          "",
          *open_questions.map { |question| "- #{question}" } ]
      end

      # CR-003. This section had the same two defects as the specification, and the review found
      # them only in `spec.md` — so fixing it there and not here would have left the business
      # analysis asserting "Criterion 2 (idempotency) is not in the ticket. It is included
      # because…" for a ticket whose criteria are lettered `a)`–`f)` and which asks for no such
      # thing. Six invented criterion numbers, and one of them justifying the exact
      # fabrication must-fix 1 removes.
      #
      # Where the ticket states its criteria, the rationale is the reporter's and this section
      # says so instead of explaining a numbering nobody wrote.
      def criteria_rationale
        return stated_criteria_rationale if ticket.acceptance_criteria?

        [
          "The ticket states no criteria of its own, so the ones in the specification are DERIVED",
          "and unconfirmed. They are written against what a reviewer can observe, because the",
          "recorded inputs describe an outcome rather than a mechanism:",
          "",
          "- The first is the ticket's actual request, stated as something demonstrable.",
          "- The rest tie the delivered behaviour back to the recorded inputs and to the existing",
          "  suites, so \"it works\" cannot be satisfied by breaking something adjacent, and an",
          "  input that was captured but quietly ignored shows up as an unmet criterion rather",
          "  than as nothing.",
          criteria_rationale_tail
        ].join("\n")
      end

      def stated_criteria_rationale
        [
          "**The criteria are the reporter's own**, reproduced verbatim in",
          "[`#{PackagePath::SPEC_MD}`](../#{PackagePath::SPEC_MD}) from the ticket's",
          "\"#{ticket.heading_for(TicketSections::ACCEPTANCE)}\" section. This generation added none",
          "of its own and does not restate their rationale — the reporter wrote them, and a",
          "paraphrase here would be a second, competing account of what \"done\" means.",
          "",
          "What this analysis can say about them:",
          "",
          "- They are the authority for acceptance. Anything an implementer cannot demonstrate",
          "  against one of them is out of scope by the ticket's own reckoning.",
          "- Two conditions hold beyond them for any generated specification: the existing suites",
          "  still pass, and every input marked *used* is reflected in the delivered behaviour.",
          criteria_rationale_tail
        ].join("\n")
      end

      def criteria_rationale_tail
        return "" if open_questions.empty?

        "- The open questions block implementation, so a guess cannot enter the\n" \
          "  codebase as though it were an approved decision."
      end

      def input_conflicts
        return no_conflict_text if unused_inputs.empty? && bundle_warnings.empty?

        [
          "Not everything the bundle recorded reached this specification. Each gap below is a real",
          "limit on how much this document can be trusted:",
          "",
          *unused_inputs.map { |input| "- **#{input['kind']}#{input_name_suffix(input)}** — #{input['note']}." },
          *bundle_warnings.map { |warning| "- #{warning}" },
          "",
          "None of this was smoothed over: an input that could not be read is recorded as not read,",
          "and any product detail that existed only in that material is missing from the",
          "specification rather than invented."
        ].join("\n")
      end

      def no_conflict_text
        [
          "None found. Every input the bundle recorded was readable and was used, and the recorded",
          "material does not contradict itself on any point this specification relies on.",
          "",
          "This is a statement about the RECORDED inputs only. It is not a claim that the ticket is",
          "complete — see the open questions in the specification for what the inputs do not decide."
        ].join("\n")
      end

      def recommendation
        return recommendation_clarification if unused_inputs.any?
        return recommendation_warnings if open_questions.any?

        [
          "**Ready to approve.**",
          "",
          "Every recorded input was readable and used, the structural and semantic evidence behind",
          "the technical analysis is present, and the recorded material decides everything the",
          "specification asserts. A reviewer should still read it — this recommendation is about the",
          "completeness of the inputs, not the quality of the design."
        ].join("\n")
      end

      def recommendation_warnings
        [
          "**Approve with warnings.**",
          "",
          "The recorded inputs were all readable, but they do not decide #{open_questions.length}",
          "#{open_questions.length == 1 ? 'question' : 'questions'} the implementation will hit (listed above",
          "and in the specification). Approving without answering them delegates a product decision to",
          "whoever writes the code."
        ].join("\n")
      end

      def recommendation_clarification
        [
          "**Needs product clarification.**",
          "",
          "#{unused_inputs.length} recorded #{unused_inputs.length == 1 ? 'input' : 'inputs'} could not be",
          "read by this runner, so material the reporter attached is not represented in this",
          "specification. Approving it would approve a document that is knowingly incomplete. Either",
          "make that material readable and regenerate, or confirm it is not needed."
        ].join("\n")
      end

      # ------------------------------------------------------ analysis/technical.md

      def technical_analysis
        <<~MD
          # Technical analysis — #{issue_key}

          - Jira issue: [#{issue_key}](#{issue_url})
          - Specification: [`#{PackagePath::SPEC_MD}`](../#{PackagePath::SPEC_MD})
          - Source checkout inspected: `#{repository}` (read-only; nothing was modified)
          - Generated locally by the SpecRelay runner; not reviewed and not published.

          ## Source entry points inspected

          #{entry_points_section}

          ## Graphify evidence

          #{tool_section('graphify')}

          ## Context+ evidence

          #{tool_section('context_plus')}

          ## Dependency and blast-radius assessment

          #{blast_radius}

          ## Likely implementation approach

          #{implementation_approach}

          ## Implementation surface

          #{implementation_surface}

          ## Tests a future implementation ticket needs

          #{tests_needed}

          ## Technical risks, unknowns, and blocked evidence

          #{technical_risks}
        MD
      end

      def entry_points_section
        return "**No source file could be read in the inspected checkout, and this generation " \
               "proceeded without one.** That is itself a finding: either the workspace mapping " \
               "points at the wrong directory, or every file under it is binary, oversized, or " \
               "excluded. Nothing below is grounded in code — it is inferred from the ticket. The " \
               "run carries a warning saying so." if entry_points.empty?

        [
          "A read-only inspection of the `#{repository}` checkout. Paths are repository-relative;",
          "the runner's local checkout location is deliberately not recorded.",
          "",
          *entry_points.first(25).map { |path| "- `#{path}`" },
          entry_points_tail
        ].compact.join("\n")
      end

      def entry_points_tail
        return nil if entry_points.length <= 25

        "\n…and #{entry_points.length - 25} further source files in the sampled tree."
      end

      # "Contributed" / "did not contribute", never "used". A tool that was declared available
      # and never queried was previously printed as `Result: used`, which is the single
      # sentence a reader would take as evidence that a semantic pass had happened.
      def tool_section(name)
        tool = tool_entry(name)
        verdict = tool["contributed"] ? "contributed evidence" : "did NOT contribute evidence"
        [
          "**Result: #{verdict}.** #{tool['summary']}",
          "",
          tool_detail(tool)
        ].join("\n")
      end


      def issue_key = issue["key"].to_s
      def issue_url = issue["url"].to_s
      def repository = source["repository"].to_s
      def entry_points = Array(source["entry_points"])

      # CR-002 must-fix 2. The document asserted source grounding in three places
      # unconditionally, while the inspection had returned zero files and the technical
      # analysis said "Nothing below is grounded in code". A specification that claims to have
      # been written against a checkout it never read is worse than one that admits it did not,
      # because only the second lets a reader discount it correctly.
      def inspected_source? = entry_points.any?

      def grounding_clause
        return " and from a read-only inspection of the `#{repository}` checkout" if inspected_source?

        " ALONE — no source file in the `#{repository}` checkout could be read, so nothing below " \
          "is grounded in code"
      end

      def generated_by
        return "the SpecRelay runner, from the input bundle and the `#{repository}` source checkout" if
          inspected_source?

        "the SpecRelay runner, from the input bundle ONLY — no source file in the " \
          "`#{repository}` checkout could be read"
      end

      def generation_caveat
        return "This specification was generated from the recorded Jira inputs and a read-only " \
               "inspection of the source checkout. It has not been approved, and no branch, commit, " \
               "pull request, or Jira update exists for it." if inspected_source?

        "**No source was inspected.** This specification was generated from the recorded Jira inputs " \
          "alone: the configured source checkout yielded no readable file, so every technical " \
          "statement below is an inference from the ticket rather than from code. It has not been " \
          "approved, and no branch, commit, pull request, or Jira update exists for it."
      end
      def bundle_warnings = Array(bundle["warnings"])
      def bundle_inputs = Array(bundle["inputs"]).map(&:to_h)
      def unused_inputs = bundle_inputs.reject { |input| input["used"] }

      def title
        raw = issue["title"].to_s.strip
        raw.empty? ? issue_key : "#{issue_key}: #{raw}"
      end

      def summary_phrase
        raw = issue["title"].to_s.strip
        raw.empty? ? "the change recorded in its input bundle" : "\"#{raw}\""
      end

      # CONTRIBUTED, not usable — and named that way now, because the old names said `usable?`
      # while reading `contributed`, which is how the document ended up asserting "both tool
      # layers reported a usable result" about a layer that had produced nothing.
      #
      # A substituted tool is one the run was allowed to proceed without; describing its
      # substitute as the tool's own evidence is the false-negative laundering criterion 4
      # forbids. See SourceEvidence::Tool for the two verdicts.
      def tool_entry(name) = tools.find { |tool| tool["name"] == name } || {}
      def contributed?(name) = tool_entry(name)["contributed"] ? true : false
      def usable?(name) = tool_entry(name)["usable"] ? true : false
      def graphify_contributed? = contributed?("graphify")
      def context_plus_contributed? = contributed?("context_plus")

      # The reporter's description, parsed into its own sections. Memoized because six sections
      # of this document read it.
      def ticket = @ticket ||= TicketSections.parse(reported_description)

      # A crude but honest heuristic, and labelled as one wherever it is used. It reads the
      # ticket's own words rather than guessing from the codebase, so a reviewer can check it.
      #
      # Two corrections, in two rounds, and the second is the one that mattered:
      #
      #   - WORD BOUNDARIES, not `include?`. Substring matching read `page` inside "homepage",
      #     `ui` inside "distinguishable" and `view` inside "REVIEW".
      #   - The ticket's INCLUSIVE material only. Word boundaries did not fix `MAPIAI-49`,
      #     because the matching mode was never the problem: its only `\bpage\b` is in "not
      #     about the page content", inside `Out of scope`. Reading an exclusion as an inclusion
      #     is a category error, and no amount of tuning the word list corrects it.
      def user_facing?
        matches_any?("#{issue['title']} #{ticket.inclusive_material}",
                     %w[button page screen ui click form field display show view])
      end

      def matches_any?(text, words)
        haystack = text.to_s.downcase
        words.any? { |word| /\b#{Regexp.escape(word)}\b/.match?(haystack) }
      end

      # The open questions this generation is willing to state. Each is derived from a real
      # gap rather than from a list of questions that could be asked about anything.
      # CR-003 must-fix 1 part 2. An open question is now suppressed only by the ticket's own
      # CRITERIA saying something about the topic — never by a keyword appearing anywhere in the
      # prose.
      #
      # Round 003 suppressed the repeat question `unless ticket_mentions_repeat?`, so the word
      # "again" in "once the file is readable again" removed the counterweight and left
      # `spec.md` reading "None arising from the recorded inputs." next to a fabricated
      # idempotency requirement. Round 002's version was contradictory but LOUD; round 003 made
      # it quiet, which is worse. A keyword match is not a product decision, and it must never
      # be able to silence a question.
      def open_questions
        @open_questions ||= begin
          questions = []
          questions << "What should happen when the operation is attempted a second time? No stated " \
                       "criterion covers repeat behaviour." unless criteria_mention_repeat?
          questions << "What should the user see when the operation cannot complete? No stated " \
                       "criterion covers the failure path." unless criteria_mention_failure?
          unused_inputs.each do |input|
            questions << "What did **#{input['kind']}#{input_name_suffix(input)}** contain? It was recorded " \
                         "as an input but could not be read here (#{input['note']})."
          end
          questions
        end
      end

      # Both heuristics read the REPORTER's description rather than the whole bundle. The
      # bundle wraps that text in SpecRelay's own scaffolding — a completeness verdict, tables
      # of read statuses and reasons — and matching a keyword there would answer "did
      # SpecRelay mention failure?" instead of "did the ticket specify one?", which is the
      # question that decides whether an open question is real.
      # These decide ONE thing each, and only one: whether to raise an open question. They no
      # longer gate any normative statement, because CR-003 established that a keyword cannot
      # carry a requirement — "again" in "readable again" is not a request for idempotency.
      #
      # They read the ticket's own CRITERIA rather than its whole description, which is the
      # narrowest text where a stated requirement can actually live. Prose discussing a failure
      # mode is not a criterion about it, and the cost of a false negative here is one extra
      # open question — the safe direction.
      def criteria_mention_repeat?
        matches_any?(ticket.acceptance_criteria, %w[idempotent idempotency idempotently twice repeat
                                                    re-run rerun duplicate duplicating])
      end

      def criteria_mention_failure?
        matches_any?(ticket.acceptance_criteria, %w[error errors fail fails failing failure invalid
                                                    reject rejects unable cannot unreadable 500])
      end

      def input_name_suffix(input)
        name = input["name"].to_s.strip
        name.empty? ? "" : " (#{name})"
      end

      def inputs_table
        return "_The bundle recorded no individual inputs._" if bundle_inputs.empty?

        rows = bundle_inputs.map do |input|
          "| #{cell(input['kind'])} | #{cell(input['name'])} | `#{cell(input['read_status'])}` | " \
            "#{input['used'] ? 'yes' : 'no'} | #{cell(input['note'])} |"
        end
        [ "| Kind | Name | Recorded read status | Used | Note |", "| --- | --- | --- | --- | --- |", *rows ].join("\n")
      end

      # The bundle is identified by its TRACE ID, never by a link.
      #
      # Platform's artifact URL is `http://127.0.0.1:3200/artifacts/…` for every local
      # operator, and this document is destined for a shared specification repository where
      # that address means a different machine to every reader — or nothing at all. The trace
      # id is stable, greppable, and correct everywhere; whoever holds the Platform instance
      # can resolve it. A dead link that looks live is worse than no link.
      def bundle_reference_line
        trace = bundle["trace_id"].to_s
        return "The bundle is the authoritative record of what the ticket offered." if trace.empty?

        "The authoritative bundle record is trace `#{trace}` in the SpecRelay Platform that " \
          "captured it."
      end

      def bundle_link
        trace = bundle["trace_id"].to_s
        trace.empty? ? "" : " (bundle trace `#{trace}`)"
      end

      def bundle_captured_clause
        trace = bundle["trace_id"].to_s
        trace.empty? ? "" : " (bundle `#{trace}`)"
      end

      # The bundle body, fenced. Fenced rather than quoted because it is Markdown itself and
      # would otherwise re-render its own headings into this document's outline.
      #
      # The fence LENGTH is chosen from the body, and that is not a detail. The bundle always
      # carries a fenced block of its own — Platform's renderer puts the reporter's
      # description in one — so a hardcoded three-backtick fence closed on the bundle's fence
      # and left the remaining six sections of this document inside a code block that was
      # never closed. That shipped. See Markdown.fenced, which is now the only sanctioned way
      # to embed text this process did not author.
      def bundle_block
        body = bundle["content_markdown"].to_s.strip
        return "_The bundle recorded no rendered content._" if body.empty?

        Markdown.fenced(body, info: "markdown")
      end

      # What the REPORTER actually wrote, pulled out of the rendered bundle.
      #
      # The bundle is a structured document — a completeness verdict, an issue table, a
      # classified-input table, the repository target, and only then the reporter's own text
      # under `## Jira description` in a fenced block. Taking "the first substantive
      # paragraph" therefore quoted "Every expected input was readable." as the problem
      # statement, which the live evidence pass caught: a specification whose Problem section
      # quotes SpecRelay's own bookkeeping is exactly the ungrounded prose scope 3 forbids.
      #
      # The section heading is part of Jira::SpecCreation::Markdown's rendered shape, so
      # reading it is reading the contract. The paragraph fallback remains for a bundle
      # rendered without one.
      DESCRIPTION_HEADING = "## Jira description"

      # The fence around that section is NOT always three backticks: Platform lengthens it
      # when the reporter's own text contains a backtick run. Matching a fixed ``` here would
      # quietly fall through to the paragraph heuristic for exactly the descriptions most
      # likely to contain code — so the opening run is captured and the closing one matched
      # against it.
      DESCRIPTION_BODY = /^(`{3,})[^\n`]*\n(.*?)\n\1`*[ \t]*$/m

      def reported_description
        body = bundle["content_markdown"].to_s
        section = body.split(DESCRIPTION_HEADING, 2)[1]
        fenced = section.to_s[DESCRIPTION_BODY, 2]
        (fenced || first_prose_paragraph(body)).to_s.strip
      end

      def first_prose_paragraph(body)
        body.split(/\n{2,}/).map(&:strip)
            .reject { |part| part.empty? || part.start_with?("#", "|", "-", "```") }.first.to_s
      end

      # A short, quoted excerpt for the prose sections. Kept to the first paragraph of the
      # reporter's text: the whole bundle already appears once under "Input summary", and
      # repeating it in full would bury the analysis.
      def quoted_bundle_excerpt
        paragraph = reported_description.split(/\n{2,}/).first.to_s.strip
        return "> _The bundle recorded no prose describing the request._" if paragraph.empty?

        paragraph.lines.map { |line| "> #{line.chomp}" }.join("\n")
      end

      def cell(value) = value.to_s.gsub("|", "\\|").gsub(/\s+/, " ").strip
    end
  end

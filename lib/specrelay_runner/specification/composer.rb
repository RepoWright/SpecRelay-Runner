      end

      def security_assessment
        "No credential, permission, or trust-boundary change is described in the recorded inputs."
      end

      # No invented criterion numbers here either (CR-003 should-fix 2). Every bullet is a test
      # any change of this shape needs, or is anchored to the criteria as a body.
      def tests_needed
        [
          "- **One test per criterion.** #{criteria_test_sentence}",
          "- A happy-path test at the level the behaviour lives at, not one level below it.",
          "- Regression coverage for the adjacent behaviour the ticket's exclusions protect —",
          "  see \"Non-goals\" in [`#{PackagePath::SPEC_MD}`](../#{PackagePath::SPEC_MD}).",
          "- If the change turns out to be user-facing, a test at that surface — a passing unit test",
          "  does not establish that a user flow works.",
          "- The repository's existing suites, run unchanged, as the baseline the change must not move."
        ].join("\n")
      end

      def criteria_test_sentence
        return "The ticket states its criteria under " \
               "\"#{ticket.heading_for(TicketSections::ACCEPTANCE)}\"; each one should be demonstrable " \
               "by a named test, referred to by the ticket's own label." if ticket.acceptance_criteria?

        "The criteria in [`#{PackagePath::SPEC_MD}`](../#{PackagePath::SPEC_MD}) are DERIVED and " \
          "unconfirmed; confirm them before writing tests against them."
      end

      def technical_risks
        lines = [
          inspection_risk,
          "- **The specification's open questions are technical risks too** — an unanswered product",
          "  decision usually becomes an arbitrary implementation choice."
        ]
        lines << "- **Blocked evidence:** #{blocked_evidence_sentence}" if blocked_evidence?
        lines << "- No evidence was blocked for this package: every recorded input was readable and " \
                 "every tool layer contributed." unless blocked_evidence?
        lines.join("\n")
      end

      # The first risk a reader meets, and it changes completely depending on whether any code
      # was read. "The entry-point list is a sample" is reassuring and wrong when the list is
      # empty.
      def inspection_risk
        return "- **The entry-point list is a sample, not an index.** It proves the checkout was\n" \
               "  inspected; it does not prove the owning code is in it." if inspected_source?

        "- **NO SOURCE WAS INSPECTED.** This is the largest risk in this document. Every technical\n" \
          "  statement below is inferred from the ticket rather than read from code, and an\n" \
          "  implementer should treat the whole analysis as a starting hypothesis."
      end

      def blocked_evidence?
        !graphify_contributed? || !context_plus_contributed? || unused_inputs.any? || !inspected_source?
      end

      # Deliberately reports CONTRIBUTION. A capability the runner cannot probe is always a
      # gap in this document's evidence, even when the operator declared it available — that
      # declaration is what the runner is allowed to proceed on, not what it may claim to have
      # gathered.
      def blocked_evidence_sentence
        parts = []
        parts << "the structural graph contributed nothing" unless graphify_contributed?
        parts << "no Context+ semantic query was performed by this process" unless context_plus_contributed?
        parts << "#{unused_inputs.length} recorded #{unused_inputs.length == 1 ? 'input' : 'inputs'} could not be read" if
          unused_inputs.any?
        "#{parts.join('; ')}. Conclusions that would have depended on that material are absent rather " \
          "than estimated."
      end

